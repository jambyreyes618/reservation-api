        <h1 id="introduction">Introduction</h1>
<p>RESTful API documentation for the Reservation system.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost:8000</code>
</aside>
<p>This documentation aims to provide all the information you need to work with our API.</p>
<p>As you scroll, you'll see code examples for working with the API in different programming languages in the right panel (or below on mobile). You can switch languages using the tabs at the top right.</p>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_AUTH_KEY}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Log in with POST /api/v1/login and paste the token here.</p>

        <h1 id="authentication">Authentication</h1>

    <p>Register, log in, refresh and log out.</p>

